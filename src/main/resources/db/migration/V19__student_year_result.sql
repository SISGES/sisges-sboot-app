-- SISGES - Year-end student result and promotion log

CREATE TABLE IF NOT EXISTS sisges.student_year_result (
    id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_cycle_id     INTEGER      NOT NULL,
    student_id            INTEGER      NOT NULL,
    source_class_id       INTEGER      NOT NULL,
    next_class_id         INTEGER,
    base_score            NUMERIC(8,2) NOT NULL,
    final_score           NUMERIC(8,2) NOT NULL,
    year_recovery_score   NUMERIC(8,2),
    approved              BOOLEAN      NOT NULL,
    promoted              BOOLEAN      NOT NULL,
    created_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_student_year_result_cycle FOREIGN KEY (academic_cycle_id)
        REFERENCES sisges.academic_cycle (id) ON DELETE CASCADE,
    CONSTRAINT fk_student_year_result_student FOREIGN KEY (student_id)
        REFERENCES sisges.student (id) ON DELETE CASCADE,
    CONSTRAINT fk_student_year_result_source_class FOREIGN KEY (source_class_id)
        REFERENCES sisges.school_class (id) ON DELETE RESTRICT,
    CONSTRAINT fk_student_year_result_next_class FOREIGN KEY (next_class_id)
        REFERENCES sisges.school_class (id) ON DELETE SET NULL,
    CONSTRAINT uq_student_year_result_cycle_student UNIQUE (academic_cycle_id, student_id)
);

CREATE INDEX IF NOT EXISTS idx_student_year_result_cycle
    ON sisges.student_year_result (academic_cycle_id);
CREATE INDEX IF NOT EXISTS idx_student_year_result_student
    ON sisges.student_year_result (student_id);

